const dictionaries: Record<AppLanguage, Dictionary> = { "zh-CN": zhCN, "zh-TW": zhTW, en, de };

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  const template = dictionaries[language]?.[key] ?? zhCN[key];
  if (!values) return template;
  return template.replace(/\{([^}]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

export function localeFor(language: AppLanguage): string {
  return language;
}

export function useI18n(): {
  language: AppLanguage;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
} {
  const language = useCompass((state) => state.settings?.language ?? "zh-CN");
  return {
    language,
    t: (key, values) => translate(language, key, values),
  };
}
